// Keep the Edge Functions' copy of the receipt engine, schema and prompt in step with
// their sources. Deno can't import across the repo, so the pure engine in
// packages/core/src/receipt/ is copied into supabase/functions/_shared/receipt/
// (with explicit .ts extensions, as Deno and Node ESM both require), the JSON schema
// from design/receipt/ is copied next to receipt-parse, and the versioned prompt
// markdown becomes an importable TS string.
//
//   node scripts/sync-functions.mjs          # write
//   node scripts/sync-functions.mjs --check  # exit 1 when anything is out of date
//
// packages/core/test/functions-sync.test.ts runs the check on every test run.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = "// GENERATED by scripts/sync-functions.mjs from %s - do not edit here.\n";

export function plan() {
  const out = [];
  const engineDir = path.join(root, "packages/core/src/receipt");
  for (const f of fs.readdirSync(engineDir).filter((f) => f.endsWith(".ts")).sort()) {
    const src = fs.readFileSync(path.join(engineDir, f), "utf8");
    const body = src.replace(/from "(\.\/[a-z-]+)"/g, 'from "$1.ts"');
    out.push({ to: `supabase/functions/_shared/receipt/${f}`, content: HEADER.replace("%s", `packages/core/src/receipt/${f}`) + body });
  }
  const schema = JSON.parse(fs.readFileSync(path.join(root, "design/receipt/receipt-extraction.schema.json"), "utf8"));
  out.push({ to: "supabase/functions/receipt-parse/schema.json", content: JSON.stringify(schema, null, 2) + "\n" });
  const promptDir = path.join(root, "supabase/functions/receipt-parse/prompts");
  for (const f of fs.readdirSync(promptDir).filter((f) => /^receipt-extraction\.v\d+\.md$/.test(f)).sort()) {
    const version = f.match(/\.(v\d+)\.md$/)[1];
    const text = fs.readFileSync(path.join(promptDir, f), "utf8");
    out.push({ to: `supabase/functions/receipt-parse/prompts/${f.replace(/\.md$/, ".ts")}`, content: HEADER.replace("%s", `prompts/${f}`) + `export const PROMPT_VERSION = ${JSON.stringify(version)};\nexport const INSTRUCTIONS = ${JSON.stringify(text)};\n` });
  }
  return out;
}

export function stale() {
  return plan().filter((p) => { const abs = path.join(root, p.to); return !fs.existsSync(abs) || fs.readFileSync(abs, "utf8") !== p.content; }).map((p) => p.to);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const s = stale();
    if (s.length) { console.error("out of date:\n  " + s.join("\n  ") + "\nrun: node scripts/sync-functions.mjs"); process.exit(1); }
    console.log("functions in sync");
  } else {
    for (const p of plan()) { const abs = path.join(root, p.to); fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, p.content); console.log("wrote", p.to); }
  }
}
