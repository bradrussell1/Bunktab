// Generates src/components/zebraArt.ts from design/zebra/svg/zebra-bust-*.svg.
// The masters' hex values become --zs-zebra-* custom properties so the web zebra
// is the same artwork as the app's, under the same tokens. Run: node scripts/build-zebra-art.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const svgDir = join(here, "../../../design/zebra/svg");
const out = join(here, "../src/components/zebraArt.ts");
const moods = ["hi", "happy", "wink", "sleepy", "starry", "love", "worried"];
const vars = {
  "#1D1A17": "var(--zs-zebra-ink)",
  "#FFFBF2": "var(--zs-zebra-hide)",
  "#9B9590": "var(--zs-zebra-muzzle)",
  "#ABA59F": "var(--zs-zebra-muzzle-sheen)",
  "#3C3833": "var(--zs-zebra-nostril)",
  "#F5A9B8": "var(--zs-zebra-ear-inner)",
  "#F7A8BC": "var(--zs-zebra-cheek)",
  "#EFE8DC": "var(--zs-zebra-ghost-stripe)",
  "#E2FF2B": "var(--zs-zebra-star)",
  "#FF4FA3": "var(--zs-zebra-heart)",
  "#FFFFFF": "var(--zs-white)",
};
const inner = (svg) => {
  let body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  for (const [hex, v] of Object.entries(vars)) body = body.split(hex).join(v).split(hex.toLowerCase()).join(v);
  const left = body.match(/#[0-9A-Fa-f]{6}/g);
  if (left) throw new Error(`unmapped colours: ${[...new Set(left)].join(", ")}`);
  return body;
};
const entries = moods.map((m) => `  ${m}: ${JSON.stringify(inner(readFileSync(join(svgDir, `zebra-bust-${m}.svg`), "utf8")))},`);
writeFileSync(out, `// Generated by scripts/build-zebra-art.mjs from design/zebra/svg. Do not edit.
// Bust viewBox is "30 -8 200 184"; colours are --zs-zebra-* tokens (see tokens.css).
export const BUST_VIEWBOX = "30 -8 200 184";
export const BUST: Record<"hi" | "happy" | "wink" | "sleepy" | "starry" | "love" | "worried", string> = {
${entries.join("\n")}
};
`);
console.log("wrote", out);
