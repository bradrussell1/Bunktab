// Embeds assets/fonts/Figtree-{700,800}.ttf as base64 in lib/og-fonts.ts so next/og can load
// them in any runtime without file tracing. Runs with `npm run tokens` (predev/prebuild).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const b64 = (f) => readFileSync(join(here, "../assets/fonts", f)).toString("base64");
writeFileSync(join(here, "../lib/og-fonts.ts"), `// Generated by scripts/build-og-fonts.mjs from assets/fonts (Figtree, OFL 1.1). Do not edit.
const decode = (s: string) => Uint8Array.from(Buffer.from(s, "base64")).buffer;
const FIGTREE_700 = "${b64("Figtree-700.ttf")}";
const FIGTREE_800 = "${b64("Figtree-800.ttf")}";
export const ogFonts = () => [
  { name: "Figtree", data: decode(FIGTREE_700), weight: 700 as const, style: "normal" as const },
  { name: "Figtree", data: decode(FIGTREE_800), weight: 800 as const, style: "normal" as const },
];
`);
console.log("og-fonts.ts written");
